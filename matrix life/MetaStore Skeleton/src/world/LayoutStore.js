/**
 * 展厅布局存储。
 */
export class LayoutStore {
  /**
   * 读取布局（无存档返回默认）。
   * 若存的是旧格式（含 shops / street），视为无效并返回默认单屋布局。
   * @returns {Object}
   */
  static load() {
    try {
      const raw = localStorage.getItem(CONFIG.admin.layoutStorageKey);
      if (raw) {
        const parsed = JSON.parse(raw);
        // 校验是否为新格式（exhibits + hall）
        if (Array.isArray(parsed.exhibits) && parsed.exhibits.length > 0 && parsed.hall) {
          return parsed;
        }
        console.warn('[LayoutStore] 检测到旧街店格式布局，已忽略并使用默认单屋布局');
        localStorage.removeItem(CONFIG.admin.layoutStorageKey);
      }
    } catch (err) {
      console.warn('[LayoutStore] 读取布局失败:', err);
    }
    return this.defaultLayout();
  }

  /**
   * 保存布局。
   * @param {Object} layout
   */
  static save(layout) {
    try {
      localStorage.setItem(CONFIG.admin.layoutStorageKey, JSON.stringify(layout));
    } catch (err) {
      console.warn('[LayoutStore] 保存布局失败:', err);
    }
  }

  /**
   * 重置布局。
   */
  static reset() {
    localStorage.removeItem(CONFIG.admin.layoutStorageKey);
  }

  /**
   * 默认单屋布局。
   *
   * 8 个展台在大厅内按 2 行 × 4 列排布：
   *   列 x = -6, -2, 2, 6  (间距 4m)
   *   行 z = -4, +4        (间距 8m)
   * 玩家从南端 z=+8 出生，面朝 -z 直视展品。
   *
   * @returns {Object}
   */
  static defaultLayout() {
    const cats = ['product-1', 'product-2', 'product-3', 'product-4', 'product-5', 'product-6', 'product-7', 'product-8'];
    const colX = [-6, -2, 2, 6];
    const rowZ = [-4, 4];
    const exhibits = [];

    let i = 0;
    for (let r = 0; r < rowZ.length; r++) {
      for (let c = 0; c < colX.length; c++) {
        const x = colX[c];
        const z = rowZ[r];
        const productId = cats[i];
        exhibits.push({
          id: `exhibit-${i + 1}`,
          productId,
          name: PRODUCT_CATALOG[productId]?.name ?? `展品 ${i + 1}`,
          position: [x, 0, z],
          facing: 0, // 朝 +z（玩家入口方向）
          vitrine: { position: [x, 0, z] },
        });
        i++;
      }
    }

    return {
      hall: { ...HALL },
      exhibits,
      spawn: { position: [0, 1.6, 8], yaw: 0 }, // 南端出生，面朝展厅中央
    };
  }
}
