/** 大厅几何参数（已放大以容纳 16 件展品，4 列 × 4 行） */
export const HALL = Object.freeze({
  width: 22,     // x 方向总长
  depth: 26,     // z 方向总长
  height: 5,     // 墙高
  wallThickness: 0.4, // 墙厚
  spawnMargin: 0.4,  // 出生点离墙的安全边距
});

/**
 * 展厅布局存储。
 */
export class LayoutStore {
  /**
   * 读取布局（无存档返回默认）。
   * 若存的是旧格式（含 shops / street），视为无效并返回默认单屋布局。
   * @returns {Object}
   */
  static load() {
    try {
      const raw = localStorage.getItem(CONFIG.admin.layoutStorageKey);
      if (raw) {
        const parsed = JSON.parse(raw);
        // 校验是否为新格式（exhibits + hall）
        if (Array.isArray(parsed.exhibits) && parsed.exhibits.length > 0 && parsed.hall) {
          return parsed;
        }
        console.warn('[LayoutStore] 检测到旧街店格式布局，已忽略并使用默认单屋布局');
        localStorage.removeItem(CONFIG.admin.layoutStorageKey);
      }
    } catch (err) {
      console.warn('[LayoutStore] 读取布局失败:', err);
    }
    return this.defaultLayout();
  }

  /**
   * 保存布局。
   * @param {Object} layout
   */
  static save(layout) {
    try {
      localStorage.setItem(CONFIG.admin.layoutStorageKey, JSON.stringify(layout));
    } catch (err) {
      console.warn('[LayoutStore] 保存布局失败:', err);
    }
  }

  /**
   * 重置布局。
   */
  static reset() {
    localStorage.removeItem(CONFIG.admin.layoutStorageKey);
  }

  /**
   * 默认单屋布局。
   *
   * N 个展台在大厅内按「4 列 × 行」网格排布（默认 16 件 -> 4×4）：
   *   列 x = [-6, -2, 2, 6]  (间距 4m)
   *   行 z 在 [-9, 9] 之间均匀铺开
   * 玩家从南端 z≈+11.5 出生，面朝 -z 直视展品。
   *
   * @returns {Object}
   */
  static defaultLayout() {
    const cats = [
      'product-1', 'product-2', 'product-3', 'product-4',
      'product-5', 'product-6', 'product-7', 'product-8',
      'product-9', 'product-10', 'product-11', 'product-12',
      'product-13', 'product-14', 'product-15', 'product-16',
    ];
    const COLS = 4;
    const ROWS = Math.ceil(cats.length / COLS);
    const colX = [-6, -2, 2, 6];
    const zTop = -9, zBot = 9; // 行在深度方向铺开
    const rowZ = [];
    for (let r = 0; r < ROWS; r++) {
      rowZ.push(ROWS === 1 ? 0 : zTop + (zBot - zTop) * (r / (ROWS - 1)));
    }

    const exhibits = [];
    let i = 0;
    for (let r = 0; r < ROWS; r++) {
      for (let c = 0; c < COLS && i < cats.length; c++) {
        const x = colX[c];
        const z = rowZ[r];
        const productId = cats[i];
        exhibits.push({
          id: `exhibit-${i + 1}`,
          productId,
          name: PRODUCT_CATALOG[productId]?.name ?? `展品 ${i + 1}`,
          position: [x, 0, z],
          facing: 0, // 朝 +z（玩家入口方向）
          vitrine: { position: [x, 0, z] },
        });
        i++;
      }
    }

    return {
      hall: { ...HALL },
      exhibits,
      spawn: { position: [0, 1.6, HALL.depth / 2 - 1.5], yaw: 0 }, // 南端出生，面朝展厅中央
    };
  }
}
